#!/usr/bin/env python3
"""Write the integer model in the BBC Micro's layout.

  build/model.bin      weights/biases/tables, loaded straight after the code
  build/model_consts.6502  BeebAsm include: sizes and shifts
  build/model_data.6502    BeebAsm include: the address of every array, per-layer table

Matrices are stored column by column with each weight biased by +128, so the
6502 can use the weight directly as the Y index into its quarter-square table.
Biases are split into a low-byte array and a high-byte array.
"""
import json, sys, os
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from intref import IntModel, EXP, EXP_LEN

src = sys.argv[1] if len(sys.argv) > 1 else "build/model.npz"
m = IntModel(src)
blob = bytearray(); labels = []; consts = {}


def put(name, data):
    labels.append((name, len(blob))); blob.extend(bytes(data))


def u8(a): return [int(v) & 0xFF for v in np.asarray(a).ravel()]


def matrix(name, p):
    W = p["W"]                                   # rows x cols
    put(name + "_w", [(int(v) + 128) & 0xFF for v in W.T.ravel()])   # column-major, +128
    b = p["b"]
    put(name + "_bl", [int(v) & 0xFF for v in b]); put(name + "_bh", [(int(v) >> 8) & 0xFF for v in b])


for l, L in enumerate(m.layers):
    qkv = dict(W=np.concatenate([L["q"]["W"], L["k"]["W"], L["v"]["W"]]),
               b=np.concatenate([L["q"]["b"], L["k"]["b"], L["v"]["b"]]))
    matrix(f"l{l}_qkv", qkv); matrix(f"l{l}_o", L["o"]); matrix(f"l{l}_f1", L["f1"]); matrix(f"l{l}_f2", L["f2"])
    put(f"l{l}_rb", u8(L["rb"]))                 # H x T, signed
put("emb", u8(m.E))                              # V x d, signed, row per token
matrix("out", m.out)
put("rtab", [m.R[i] for i in range(64, 256)])    # RMSNorm 1/sqrt table for m = 64..255
put("exptab", EXP)                               # 64 entries

c = dict(D=m.d, NH=m.H, HD=m.hd, NL=m.L, FF=m.F, CTX=m.T, NV=m.V, NK=m.NK, EMB_SHIFT=m.emb_shift,
         SL=m.out["S"], EXP_LEN=EXP_LEN)
nparams = sum(int(np.asarray(v).size) for L in m.layers for k in ("q", "k", "v", "o", "f1", "f2") for v in (L[k]["W"], L[k]["b"])) \
    + sum(L["rb"].size for L in m.layers) + m.E.size + m.out["W"].size + m.out["b"].size
open("build/model.bin", "wb").write(blob)
with open("build/model_consts.6502", "w") as f:
    f.write(f"\\ generated by tools/export_beeb.py from {src} - do not edit\n")
    for k, v in c.items(): f.write(f"{k} = {v}\n")
    f.write("MODEL_SIZE = %d\n" % len(blob))
    f.write("NPARAMS_K = %d\n" % round(nparams / 1000))
with open("build/model_data.6502", "w") as f:
    f.write(f"\\ generated by tools/export_beeb.py from {src} - do not edit\n")
    for name, off in labels: f.write(f"{name} = model + {off}\n")
    f.write("\\ per-layer table: qkv_w qkv_bl o_w o_bl f1_w f1_bl f2_w f2_bl rb (words), then shifts\n")
    f.write(".layer_tab\n")
    for l, L in enumerate(m.layers):
        f.write(f"  EQUW l{l}_qkv_w, l{l}_qkv_bl, l{l}_o_w, l{l}_o_bl, l{l}_f1_w, l{l}_f1_bl, l{l}_f2_w, l{l}_f2_bl, l{l}_rb\n")
        f.write(f"  EQUW kcache + {l} * HD * CTX, vcache + {l} * HD * CTX\n")
        f.write(f"  EQUB {L['q']['S']}, {L['k']['S']}, {L['v']['S']}, {L['o']['S'] & 0xFF}, {L['f1']['S']}, {L['f2']['S'] & 0xFF}, {L['SQK']}, 0\n")
    f.write("LAYER_TAB_SIZE = 30\n")
info = dict(c, model_bytes=len(blob), params=int(nparams), source=src)
json.dump(info, open("build/model_info.json", "w"), indent=1)
print(f"model.bin {len(blob)} bytes, {nparams} parameters; shifts:",
      [(L['q']['S'], L['k']['S'], L['v']['S'], L['o']['S'], L['f1']['S'], L['f2']['S'], L['SQK']) for L in m.layers], "SL", m.out["S"])
